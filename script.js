function pickStudent() {
  const input =
    document.getElementById("studentNames");

  if (!input) return;

  const names = input.value.trim();

  if (!names) {
    document.getElementById("studentResult")
      .textContent = "Есімдерді енгізіңдер.";
    return;
  }

  if (unusedStudents.length === 0) {
    unusedStudents = names
      .split(/[,;\n]+/)
      .map(item => item.trim())
      .filter(Boolean);
  }

  if (!unusedStudents.length) return;

  const index = Math.floor(
    Math.random() * unusedStudents.length
  );

  const chosen = unusedStudents.splice(index, 1)[0];

  document.getElementById("studentResult")
    .textContent =
    "Таңдалған студент: " + chosen;
}

