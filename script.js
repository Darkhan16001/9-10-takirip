const STORAGE_KEY = "darkhan-history-9-10-scores";

let awards = [{}, {}, {}];

try {
  const saved = JSON.parse(
    localStorage.getItem(STORAGE_KEY)
  );

  if (
    Array.isArray(saved) &&
    saved.length === 3 &&
    saved.every(item =>
      item !== null &&
      typeof item === "object" &&
      !Array.isArray(item)
    )
  ) {
    awards = saved;
  }
} catch (error) {
  awards = [{}, {}, {}];
}

function saveScores() {
  try {
    localStorage.setItem(
      STORAGE_KEY,
      JSON.stringify(awards)
    );
  } catch (error) {
    // Сақтау мүмкін болмаған жағдайда
    // сайт жұмысын жалғастырады.
  }
}

function teamScore(index) {
  return Object.values(awards[index]).reduce(
    (sum, value) =>
      sum + (Number.isFinite(value) ? value : 0),
    0
  );
}

function updateScoreboard() {
  document.getElementById("scoreboard").innerHTML =
    awards.map((team, index) => `
      <div class="score-row">
        <span>${index + 1}-команда</span>
        <strong>${teamScore(index)} ұпай</strong>
      </div>
    `).join("");

  if (currentStage === 7) {
    renderFinalScores();
  }
}

function awardButton(team, key, points) {
  const active = Boolean(awards[team][key]);

  return `
    <button
      class="award ${active ? "active" : ""}"
      data-award="${team}|${key}|${points}"
    >
      ${active ? "✓ Ұпай берілді" : "+" + points + " ұпай"}
    </button>
  `;
}

function toggleAward(team, key, points) {
  if (!awards[team]) return;

  if (awards[team][key]) {
    delete awards[team][key];
  } else {
    awards[team][key] = points;
  }

  saveScores();
  updateScoreboard();

  document.querySelectorAll("[data-award]")
    .forEach(button => {
      const [t, k, p] =
        button.dataset.award.split("|");

      const active = Boolean(
        awards[Number(t)][k]
      );

      button.classList.toggle("active", active);
      button.textContent = active
        ? "✓ Ұпай берілді"
        : "+" + p + " ұпай";
    });
}

function resetScores() {
  if (!confirm("Ұпайларды нөлдейміз бе?")) {
    return;
  }

  awards = [{}, {}, {}];

  saveScores();
  updateScoreboard();

  if (currentStage === 6) {
    showPage(6);
  }
}

document.getElementById("resetScores")
  .addEventListener("click", resetScores);

