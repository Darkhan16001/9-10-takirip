function renderVideo() {
  const container =
    document.getElementById("videoContainer");

  if (!container) return;

  container.innerHTML = videoHTML();

  const selected =
    document.getElementById("videoModeButtons");

  if (selected) {
    selected.querySelectorAll("[data-video]")
      .forEach(button => {
        button.classList.toggle(
          "active",
          button.dataset.video === videoMode
        );
      });
  }

  const video = document.getElementById("railwayVideo");

  if (video) {
    video.addEventListener("error", function() {
      const status = document.getElementById("videoStatus");

      if (status) {
        status.textContent =
          "Видео жүктелмеді. Қазақша бейнесабақты " +
          "немесе интерактивті түсіндірмені таңдаңдар.";
      }
    }, true);
  }
}

function changeSlide(direction) {
  currentSlide =
    (currentSlide + direction + videoSlides.length) %
    videoSlides.length;

  renderVideo();
}

