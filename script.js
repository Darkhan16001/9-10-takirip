function winnerName() {
  const scores = awards.map(
    (_, index) => teamScore(index)
  );

  const max = Math.max(...scores);

  if (max === 0) {
    return "Ұпайлар әлі қойылмады";
  }

  const winners = scores
    .map((score, index) => ({
      score,
      name: `${index + 1}-команда`
    }))
    .filter(item => item.score === max);

  if (winners.length > 1) {
    return (
      "Тең нәтиже: " +
      winners.map(item => item.name).join(", ")
    );
  }

  return "Жеңімпаз — " + winners[0].name;
}

